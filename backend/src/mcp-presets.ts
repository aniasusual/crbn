export function getMcpPreset(idOrName: string): McpPreset | undefined {
  const normalized = idOrName.toLowerCase().trim();
  return MCP_PRESETS.find(
    (p) => p.id.toLowerCase() === normalized || p.defaultName.toLowerCase() === normalized
  );
}
